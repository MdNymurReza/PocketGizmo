export const BD_PHONE_RE = /^(?:\+?88)?01[3-9]\d{8}$/;

/** Normalise to 01XXXXXXXXX */
export function normalizePhone(p: string) {
  const digits = p.replace(/\D/g, "");
  return digits.length > 11 ? digits.slice(-11) : digits;
}

